// Shared by gen-z-tokens.ts (writes src/styles/z-tokens.css) and check-z.ts (verifies it).
// `Z` in src/lib/tokens.ts is the ONLY source of z-index layer values; the CSS variables are generated.
import { Z } from '../src/lib/tokens'

/** hudSupreme -> hud-supreme, deckExpanded -> deck-expanded */
export const kebab = (name: string): string => name.replace(/[A-Z]/g, c => '-' + c.toLowerCase())

export const Z_ENTRIES: Array<[string, number]> = Object.entries(Z)

export const Z_CSS_PATH = 'src/styles/z-tokens.css'

export function renderZCss(): string {
  const width = Math.max(...Z_ENTRIES.map(([n]) => kebab(n).length))
  const lines = Z_ENTRIES.map(([n, v]) => `  --z-${kebab(n)}:${' '.repeat(width - kebab(n).length + 1)}${v};`)
  return [
    '/* GENERATED by scripts/gen-z-tokens.ts from `Z` in src/lib/tokens.ts. DO NOT EDIT BY HAND. */',
    '/* Change a layer in tokens.ts; this file is regenerated on predev/prebuild (npm run gen:z). */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n')
}
