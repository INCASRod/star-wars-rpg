/**
 * Builds data/astrogation/wook/seed.sql from graph.json + routes.json + hazards.json.
 * Idempotent SQL (INSERT ... ON CONFLICT DO UPDATE): run it through the Supabase MCP / SQL editor, no service key needed.
 *
 *   npx tsx scripts/astrogation/wook/build-seed.ts
 */
import * as fs from 'node:fs'
import * as path from 'node:path'

const DATA = path.resolve(__dirname, '..', '..', '..', 'data', 'astrogation')
const read = <T>(file: string): T => JSON.parse(fs.readFileSync(path.join(DATA, file), 'utf-8')) as T

interface GraphFile {
  nodes: { id: string; name: string; x: number; y: number; region: string | null; sector: string | null; on_lane: boolean }[]
  edges: { a: string; b: string; route: string; class: 'major' | 'minor'; length_px: number }[]
}
interface RoutesFile {
  routes: { route: string; edition_used: string; source_url: string; revision_id: number }[]
}

const q = (v: string | null) => (v === null ? 'NULL' : `'${v.replace(/'/g, "''")}'`)
const graph = read<GraphFile>('wook/graph.json')
const routes = new Map(read<RoutesFile>('wook/routes.json').routes.map(r => [r.route, r]))
const hazards = read<{ system: string; upgrades: number; note?: string }[]>('hazards.json')

const out: string[] = ['-- generated by scripts/astrogation/wook/build-seed.ts; do not edit by hand', '']

out.push('INSERT INTO ref_systems (id, name, x, y, region, sector, on_lane, source) VALUES')
out.push(graph.nodes.map(n => `(${q(n.id)},${q(n.name)},${n.x},${n.y},${q(n.region)},${q(n.sector)},${n.on_lane},'dk-map')`).join(',\n'))
out.push('ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, x = EXCLUDED.x, y = EXCLUDED.y, region = EXCLUDED.region, sector = EXCLUDED.sector, on_lane = EXCLUDED.on_lane, source = EXCLUDED.source;', '')

// one row per route article (attribution), edges refer to it by index: keeps the seed small
const used = [...new Set(graph.edges.map(e => e.route))]
used.forEach(name => {
  if (!routes.has(name)) throw new Error(`edge route not in routes.json: ${name}`)
})
out.push('WITH r(i, route_name, edition, source_url, source_revision) AS (VALUES')
out.push(used.map((name, i) => { const r = routes.get(name)!; return `(${i},${q(name)},${q(r.edition_used)},${q(r.source_url)},${r.revision_id})` }).join(',\n'))
out.push('), e(a, b, i, lane_class, length_px) AS (VALUES')
out.push(graph.edges.map(x => `(${q(x.a)},${q(x.b)},${used.indexOf(x.route)},'${x.class}',${x.length_px})`).join(',\n'))
out.push(')')
out.push('INSERT INTO ref_hyperlanes (a, b, route_name, lane_class, length_px, edition, source_url, source_revision)')
out.push('SELECT e.a, e.b, r.route_name, e.lane_class, e.length_px, r.edition, r.source_url, r.source_revision FROM e JOIN r ON r.i = e.i')
out.push('ON CONFLICT (a, b, route_name) DO UPDATE SET lane_class = EXCLUDED.lane_class, length_px = EXCLUDED.length_px, edition = EXCLUDED.edition, source_url = EXCLUDED.source_url, source_revision = EXCLUDED.source_revision;', '')

out.push('INSERT INTO ref_nav_hazards (system_id, upgrades, note) VALUES')
out.push(hazards.map(h => `(${q(h.system)},${h.upgrades},${q(h.note ?? '')})`).join(',\n'))
out.push('ON CONFLICT (system_id, note) DO UPDATE SET upgrades = EXCLUDED.upgrades;', '')

fs.writeFileSync(path.join(DATA, 'wook', 'seed.sql'), out.join('\n'))
console.log(`seed.sql: ${graph.nodes.length} systems, ${graph.edges.length} hyperlanes, ${hazards.length} hazards`)
